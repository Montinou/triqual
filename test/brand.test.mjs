test('readEnv: the TRIQUAL_ key when present, even empty, else the CM_ key', () => {
  assert.equal(readEnv({ TRIQUAL_REGISTRY_DIR: 'a', CM_REGISTRY_DIR: 'b' }, 'REGISTRY_DIR'), 'a');
  assert.equal(readEnv({ CM_REGISTRY_DIR: 'b' }, 'REGISTRY_DIR'), 'b');
  assert.equal(readEnv({ TRIQUAL_REGISTRY_DIR: '', CM_REGISTRY_DIR: 'b' }, 'REGISTRY_DIR'), '');
  assert.equal(readEnv({}, 'LOCK_TIMEOUT_MS'), undefined);
});

test('brandDir: the new dir, then the legacy dir, then the new dir, creating nothing', () => {
  const none = mkdtempSync(join(tmpdir(), 'brand-'));
  assert.equal(brandDir(none), join(none, BRAND.dir));
  assert.deepEqual(readdirSync(none), []);

  const legacy = mkdtempSync(join(tmpdir(), 'brand-'));
  mkdirSync(join(legacy, BRAND.legacy.dir));
  assert.equal(brandDir(legacy), join(legacy, BRAND.legacy.dir));
  assert.deepEqual(readdirSync(legacy), [BRAND.legacy.dir]);

  const both = mkdtempSync(join(tmpdir(), 'brand-'));
  mkdirSync(join(both, BRAND.dir));
  mkdirSync(join(both, BRAND.legacy.dir));
  assert.equal(brandDir(both), join(both, BRAND.dir));
  assert.deepEqual(readdirSync(both).sort(), [BRAND.legacy.dir, BRAND.dir].sort());
});

test('brand.mjs imports only node: built-ins', () => {
  const source = readFileSync(COPIES[0], 'utf8');
  const specifiers = [...source.matchAll(/^\s*import\b[^'"]*['"]([^'"]+)['"]/gm)].map((m) => m[1]);
  assert.ok(specifiers.length > 0);
  for (const s of specifiers) assert.match(s, /^node:/);
});
