// The single source of brand strings: the triqual names and the legacy claude-methodology ones they replace.
// Byte-identical copies live in plugins/methodology/bin/lib, plugins/progress-tracking/lib and
// plugins/memory-report/lib, because installed plugins cannot import each other. Only node: built-ins.
import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

function deepFreeze(o) {
  for (const v of Object.values(o)) if (v !== null && typeof v === 'object') deepFreeze(v);
  return Object.freeze(o);
}

export const BRAND = deepFreeze({
  marketplace: 'triqual',
  source: 'Montinou/triqual',
  cli: 'triqual',
  cliFile: 'triqual.mjs',
  launcher: 'triqual-hook',
  envPrefix: 'TRIQUAL_',
  dir: 'triqual',
  markers: { start: '<!-- triqual:start -->', end: '<!-- triqual:end -->' },
  generatedMark: '# generated by triqual from roles ',
  grokName: 'triqual',
  // Line 2 of each file we install: an existing file without it is not ours.
  ownership: {
    shim: '// The `triqual` shim.',
    launcher: '# The triqual hook launcher.',
    alias: '// The cm alias of triqual.',
    forwarder: '# The cm-hook forwarder of triqual.',
  },
  legacy: {
    marketplace: 'claude-methodology',
    cli: 'cm',
    cliFile: 'cm.mjs',
    launcher: 'cm-hook',
    envPrefix: 'CM_',
    dir: 'claude-methodology',
    markers: { start: '<!-- claude-methodology:start -->', end: '<!-- claude-methodology:end -->' },
    generatedMark: '# generated by claude-methodology from roles ',
    grokName: 'claude-methodology',
    ownership: {
      shim: '// The `cm` shim.',
      launcher: '# The claude-methodology hook launcher.',
    },
  },
});

function readPluginsJson(home, file) {
  try {
    return JSON.parse(readFileSync(join(home, '.claude', 'plugins', file), 'utf8'));
  } catch {
    return null;
  }
}

const isObject = (v) => v !== null && typeof v === 'object' && !Array.isArray(v);

// The plugin ids in installed_plugins.json; empty on any read or parse error.
export function installedIds(home) {
  const installed = readPluginsJson(home, 'installed_plugins.json');
  return new Set(isObject(installed) && isObject(installed.plugins) ? Object.keys(installed.plugins) : []);
}

// The plugin ids with at least one user-scope entry in installed_plugins.json; empty on any read or parse error.
export function userInstalledIds(home) {
  const installed = readPluginsJson(home, 'installed_plugins.json');
  if (!isObject(installed) || !isObject(installed.plugins)) return new Set();
  const atUser = (entries) => Array.isArray(entries) && entries.some((e) => isObject(e) && e.scope === 'user');
  return new Set(Object.keys(installed.plugins).filter((id) => atUser(installed.plugins[id])));
}

// The marketplace known to Claude Code: triqual, then the legacy one, then triqual when neither is known.
export function activeMarketplace(home) {
  const known = readPluginsJson(home, 'known_marketplaces.json');
  if (isObject(known) && Object.hasOwn(known, BRAND.marketplace)) return BRAND.marketplace;
  if (isObject(known) && Object.hasOwn(known, BRAND.legacy.marketplace)) return BRAND.legacy.marketplace;
  return BRAND.marketplace;
}

// The id of plugin `name` as installed, so a half-finished migration keeps working: the new id at user scope, the
// legacy id at user scope, then either one installed at any scope (new first), else under the known marketplace. A
// local- or project-scope install never hides a user-scope one, which is what hooks and the shim run outside it.
export function pluginId(home, name) {
  const current = `${name}@${BRAND.marketplace}`;
  const legacy = `${name}@${BRAND.legacy.marketplace}`;
  const atUser = userInstalledIds(home);
  if (atUser.has(current)) return current;
  if (atUser.has(legacy)) return legacy;
  const ids = installedIds(home);
  if (ids.has(current)) return current;
  if (ids.has(legacy)) return legacy;
  return `${name}@${activeMarketplace(home)}`;
}

// TRIQUAL_<suffix> when the key is present, even empty (so today's "unusable" handling still applies), else CM_<suffix>.
export function readEnv(env, suffix) {
  const key = BRAND.envPrefix + suffix;
  return Object.hasOwn(env, key) ? env[key] : env[BRAND.legacy.envPrefix + suffix];
}

// <base>/triqual when it exists, else <base>/claude-methodology when that exists, else <base>/triqual. Creates nothing.
export function brandDir(base) {
  const current = join(base, BRAND.dir);
  if (existsSync(current)) return current;
  const legacy = join(base, BRAND.legacy.dir);
  return existsSync(legacy) ? legacy : current;
}
